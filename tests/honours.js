// Palmarés por franquicia: títulos históricos, mudanzas y temporadas sin duplicación.
// Uso: node tests/honours.js; sin navegador ni red.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const storage={getItem(){return null;},setItem(){}};
const ctx=vm.createContext({window:{},document:{title:'NFLARG'},location:{hash:'#/nfl/team/9/palmares'},localStorage:storage,sessionStorage:storage,console,URL,setTimeout,clearTimeout});
vm.runInContext(html.match(/<script>([\s\S]*)<\/script>/)[1].replace(/\binit\(\);\s*$/,''),ctx);
assert.equal(vm.runInContext('typeof teamHonours',ctx),'function','Falta el palmarés de las franquicias');
const {teamHonours,teamHonoursHTML}=vm.runInContext('({teamHonours,teamHonoursHTML})',ctx);
assert.equal(vm.runInContext('parseHash().tab',ctx),'palmares','La ruta del equipo abre su palmarés');
const plain=v=>JSON.parse(JSON.stringify(v));
let m=teamHonours('9',2026);
assert.equal(m.total,13,'Green Bay no duplica sus títulos NFL/Super Bowl de 1966 y 1967');
assert.deepEqual(plain(m.sb),[1966,1967,1996,2010]);
assert.equal(m.nfl.length,11);
assert.equal(teamHonours('9',1967).total,11);
assert.equal(teamHonours('5',2026).total,8,'Browns conserva sus 4 AAFC y 4 NFL');
assert.equal(teamHonours('33',2026).total,2,'Ravens no hereda los títulos de Browns ni de Baltimore Colts');
assert.equal(teamHonours('11',2026).total,5,'Los títulos de Baltimore Colts pertenecen a Indianapolis');
assert.equal(teamHonours('10',2026).afl.length,2,'Oilers pertenece a la historia de Titans');
assert.equal(teamHonours('34',2026).total,0,'Houston Texans no hereda títulos de Oilers');
assert.equal(teamHonours('12',2026).afl.length,3,'Dallas Texans pertenece a Kansas City Chiefs');
assert.equal(teamHonours('6',2026).afl.length,0,'Dallas Cowboys no hereda títulos de Dallas Texans');
assert.equal(teamHonours('16',2026).nfl.length,1,'Minnesota ganó el campeonato NFL de 1969');
assert.equal(teamHonours('13',2026).sb.length,3,'Raiders conserva Oakland y Los Angeles');
assert.equal(teamHonours('14',2026).total,4,'Rams conserva Cleveland, Los Angeles y St. Louis');
assert.deepEqual(plain(teamHonours('26',2026).sb),[2013,2025]);
assert.deepEqual(plain(teamHonours('26',2024).sb),[2013],'Una vista histórica no muestra campeonatos futuros');
assert.equal(teamHonours('17',2026).sb.length,6);
assert.equal(teamHonours('17',2026).last,2018);
assert.equal(teamHonours('999',2026).known,false,'Un equipo desconocido no se presenta como campeón de cero títulos');
assert.equal(teamHonours('1',2026).total,0);
assert.equal(teamHonours('1',2026).last,null);
assert.ok(teamHonoursHTML('1',2026).includes('Todavía no ganó el Super Bowl'));
assert.ok(teamHonoursHTML('9',2026).includes('2010'));
const {teams}=require('./draft-fixture');
assert.equal(teams.reduce((n,t)=>n+teamHonours(t.id,2026).sb.length,0),60,'Una franquicia ganadora por cada Super Bowl I–LX');
assert.equal(teams.reduce((n,t)=>n+teamHonours(t.id,2026).nfl.length,0),44,'Campeonatos NFL de las franquicias actuales antes de la fusión');
assert.equal(teams.reduce((n,t)=>n+teamHonours(t.id,2026).afl.length,0),10);
assert.equal(teams.reduce((n,t)=>n+teamHonours(t.id,2026).aafc.length,0),4);
console.log('Palmarés: 32 franquicias, 60 Super Bowls, historia, mudanzas y corte por temporada OK');
